using System.Collections.Immutable;
using TUnit.Mocks.SourceGenerator.Models;

namespace TUnit.Mocks.SourceGenerator.Builders;

/// <summary>
/// Emits closed factory registrations for generic interface mocks named with concrete type
/// arguments, so <c>Mock.Of&lt;IRepository&lt;int&gt;&gt;()</c> never reaches the
/// <c>MakeGenericType</c> fallback in <c>MockRegistry</c>. See issue #7027.
/// </summary>
internal static class ClosedGenericRegistrationBuilder
{
    public const string HintName = "TUnit.Mocks.ClosedGenericFactories.g.cs";

    public static string Build(EquatableArray<ClosedGenericFactoryEmission> registrations)
    {
        var writer = new CodeWriter();

        writer.AppendLine("// <auto-generated/>");
        writer.AppendLine("#pragma warning disable");
        writer.AppendLine("#nullable enable");
        writer.AppendLine();
        writer.AppendLine("namespace TUnit.Mocks.Generated;");
        writer.AppendLine();

        using (writer.Block("file static class ClosedGenericMockFactories"))
        {
            writer.AppendLine("[global::System.Runtime.CompilerServices.ModuleInitializer]");
            using (writer.Block("internal static void Register()"))
            {
                foreach (var registration in registrations)
                {
                    var closedType = registration.ClosedTypeFullyQualifiedName;
                    var displayName = closedType.Replace("global::", string.Empty);

                    writer.AppendLine($"global::TUnit.Mocks.MockRegistry.RegisterFactory<{closedType}>(static (behavior, constructorArgs) =>");
                    writer.AppendLine("{");
                    writer.AppendLine($"    if (constructorArgs.Length > 0) throw new global::System.ArgumentException($\"Interface mock '{displayName}' does not support constructor arguments, but {{constructorArgs.Length}} were provided.\");");
                    writer.AppendLine($"    return {registration.FactoryMethod}(behavior);");
                    writer.AppendLine("});");
                }
            }
        }

        return writer.ToString();
    }

    /// <summary>
    /// Pairs each distinct registration with the open mock generated for it. Registrations whose
    /// open mock was not generated as a plain single-interface mock (dropped, colliding, or bridged
    /// for static abstract members) are skipped and keep using the runtime fallback.
    /// </summary>
    public static EquatableArray<ClosedGenericFactoryEmission> Resolve(
        ImmutableArray<ClosedGenericMockRegistration> registrations,
        ImmutableArray<MockTypeModel> models)
    {
        if (registrations.IsDefaultOrEmpty)
        {
            return EquatableArray<ClosedGenericFactoryEmission>.Empty;
        }

        var openModels = new Dictionary<string, MockTypeModel>(StringComparer.Ordinal);
        foreach (var model in models)
        {
            if (model is { IsInterface: true, IsPartialMock: false, IsWrapMock: false, IsDelegateType: false, IsSecondaryMemberSurface: false, HasStaticAbstractMembers: false, CollidesWith: null }
                && model.AdditionalInterfaceNames.Length == 0
                && model.TypeParameters.Length > 0)
            {
                openModels[model.FullyQualifiedName] = model;
            }
        }

        var seen = new HashSet<string>(StringComparer.Ordinal);
        var emissions = new List<ClosedGenericFactoryEmission>();
        foreach (var registration in registrations)
        {
            if (!openModels.TryGetValue(registration.OpenTypeFullyQualifiedName, out var model)
                || model.TypeParameters.Length != registration.TypeArguments.Length
                || !seen.Add(registration.ClosedTypeFullyQualifiedName))
            {
                continue;
            }

            emissions.Add(new ClosedGenericFactoryEmission(
                registration.ClosedTypeFullyQualifiedName,
                $"{MockImplBuilder.GetGlobalMockNamespacePrefix(model)}{MockImplBuilder.GetCompositeShortSafeName(model)}MockFactory.CreateAutoMock<{string.Join(", ", registration.TypeArguments)}>"));
        }

        // Ordinal order keeps the emitted file stable regardless of call-site discovery order.
        emissions.Sort(static (x, y) => StringComparer.Ordinal.Compare(x.ClosedTypeFullyQualifiedName, y.ClosedTypeFullyQualifiedName));
        return new EquatableArray<ClosedGenericFactoryEmission>(emissions.ToImmutableArray());
    }
}
