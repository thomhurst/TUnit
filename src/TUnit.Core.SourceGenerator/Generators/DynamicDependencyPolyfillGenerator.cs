using Microsoft.CodeAnalysis;

namespace TUnit.Core.SourceGenerator.Generators;

/// <summary>
/// Generated code keeps each non-public test method available to reflection under trimming with
/// <c>[DynamicDependency]</c>, but <c>System.Diagnostics.CodeAnalysis.DynamicDependencyAttribute</c> only ships
/// in .NET 5+. A .NET Standard test library can still end up in a trimmed or Native AOT application, and the
/// trimmer recognises the attribute by name in any assembly, so this generator declares it as an internal type
/// when nothing else provides it.
/// </summary>
[Generator]
public sealed class DynamicDependencyPolyfillGenerator : AttributePolyfillGenerator
{
    protected override string AttributeMetadataName => "System.Diagnostics.CodeAnalysis.DynamicDependencyAttribute";

    protected override string HintName => "TUnit.DynamicDependencyAttribute.g.cs";

    protected override string Source =>
        """
        // <auto-generated/>
        // Declared by TUnit because the project has no single usable DynamicDependencyAttribute: it is missing
        // (.NET Framework, .NET Standard) or declared by several references. The trimmer matches the attribute
        // by name, so this declaration works for trimmed and Native AOT applications. Set the
        // EnableTUnitPolyfills MSBuild property to false to opt out.
        #nullable enable
        namespace System.Diagnostics.CodeAnalysis
        {
            [global::System.AttributeUsage(global::System.AttributeTargets.Constructor | global::System.AttributeTargets.Field | global::System.AttributeTargets.Method, AllowMultiple = true, Inherited = false)]
            [global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]
            internal sealed class DynamicDependencyAttribute : global::System.Attribute
            {
                public DynamicDependencyAttribute(string memberSignature)
                {
                    MemberSignature = memberSignature;
                }

                public DynamicDependencyAttribute(string memberSignature, global::System.Type type)
                {
                    MemberSignature = memberSignature;
                    Type = type;
                }

                public DynamicDependencyAttribute(string memberSignature, string typeName, string assemblyName)
                {
                    MemberSignature = memberSignature;
                    TypeName = typeName;
                    AssemblyName = assemblyName;
                }

                public string? MemberSignature { get; }

                public global::System.Type? Type { get; }

                public string? TypeName { get; }

                public string? AssemblyName { get; }

                public string? Condition { get; set; }
            }
        }
        """;
}
