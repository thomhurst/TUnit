using Microsoft.CodeAnalysis;

namespace TUnit.Core.SourceGenerator.Generators;

/// <summary>
/// The generated test registration code runs from a <c>[ModuleInitializer]</c>, but
/// <c>System.Runtime.CompilerServices.ModuleInitializerAttribute</c> only ships in .NET 5+.
/// When a project targets .NET Framework or .NET Standard and nothing else provides the attribute,
/// or several references declare it so that it is ambiguous, this generator declares it as an internal
/// type so the generated code compiles without the project having to reference a polyfill package.
/// </summary>
[Generator]
public sealed class ModuleInitializerPolyfillGenerator : AttributePolyfillGenerator
{
    protected override string AttributeMetadataName => "System.Runtime.CompilerServices.ModuleInitializerAttribute";

    protected override string HintName => "TUnit.ModuleInitializerAttribute.g.cs";

    protected override string Source =>
        """
        // <auto-generated/>
        // Declared by TUnit because the project has no single usable ModuleInitializerAttribute: it is missing
        // (.NET Framework, .NET Standard) or declared by several references. Set the EnableTUnitPolyfills
        // MSBuild property to false to opt out.
        namespace System.Runtime.CompilerServices
        {
            [global::System.AttributeUsage(global::System.AttributeTargets.Method, Inherited = false)]
            [global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]
            internal sealed class ModuleInitializerAttribute : global::System.Attribute
            {
            }
        }
        """;
}
