using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;

namespace TUnit.Core.SourceGenerator.Generators;

/// <summary>
/// The generated test registration code runs from a <c>[ModuleInitializer]</c>, but
/// <c>System.Runtime.CompilerServices.ModuleInitializerAttribute</c> only ships in .NET 5+.
/// When a project targets .NET Framework or .NET Standard and nothing else provides the attribute,
/// this generator declares it as an internal type so the generated code compiles without the
/// project having to reference a polyfill package.
/// </summary>
/// <remarks>
/// The existence check needs the compilation, so this cannot use RegisterPostInitializationOutput.
/// Types from other source generators are invisible here, so PolySharp (the common generator-based
/// polyfill) is detected through the build properties it makes visible to the compiler instead.
/// Set <c>EnableTUnitPolyfills</c> to <c>false</c> to turn the fallback off.
/// </remarks>
[Generator]
public sealed class ModuleInitializerPolyfillGenerator : IIncrementalGenerator
{
    private const string AttributeMetadataName = "System.Runtime.CompilerServices.ModuleInitializerAttribute";

    private const string Source =
        """
        // <auto-generated/>
        // Declared by TUnit because this target framework has no ModuleInitializerAttribute and nothing else
        // in the project provides one. Set the EnableTUnitPolyfills MSBuild property to false to opt out.
        namespace System.Runtime.CompilerServices
        {
            [global::System.AttributeUsage(global::System.AttributeTargets.Method, Inherited = false)]
            [global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]
            internal sealed class ModuleInitializerAttribute : global::System.Attribute
            {
            }
        }
        """;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var allowedProvider = context.AnalyzerConfigOptionsProvider
            .Select(static (options, _) => IsAllowed(options.GlobalOptions));

        var attributeMissingProvider = context.CompilationProvider
            .Select(static (compilation, _) => !HasAccessibleAttribute(compilation));

        context.RegisterSourceOutput(attributeMissingProvider.Combine(allowedProvider), static (spc, data) =>
        {
            if (data.Left && data.Right)
            {
                spc.AddSource("TUnit.ModuleInitializerAttribute.g.cs", SourceText.From(Source, System.Text.Encoding.UTF8));
            }
        });
    }

    private static bool IsAllowed(AnalyzerConfigOptions options)
    {
        if (IsFalse(options, "build_property.EnableTUnitSourceGeneration")
            || IsFalse(options, "build_property.EnableTUnitPolyfills"))
        {
            return false;
        }

        return !PolySharpProvidesAttribute(options);
    }

    private static bool IsFalse(AnalyzerConfigOptions options, string key)
    {
        return options.TryGetValue(key, out var value)
            && string.Equals(value.Trim(), "false", StringComparison.OrdinalIgnoreCase);
    }

    // PolySharp marks its settings as compiler-visible, so the keys exist (possibly empty) whenever it is installed.
    // It generates every polyfill that is missing unless the type is filtered out by these two lists.
    private static bool PolySharpProvidesAttribute(AnalyzerConfigOptions options)
    {
        if (!options.TryGetValue("build_property.PolySharpIncludeGeneratedTypes", out var included))
        {
            return false;
        }

        if (!string.IsNullOrWhiteSpace(included) && !ListContainsAttribute(included))
        {
            return false;
        }

        return !options.TryGetValue("build_property.PolySharpExcludeGeneratedTypes", out var excluded)
            || !ListContainsAttribute(excluded);
    }

    private static bool ListContainsAttribute(string list)
    {
        foreach (var entry in list.Split([';', ','], StringSplitOptions.RemoveEmptyEntries))
        {
            if (string.Equals(entry.Trim(), AttributeMetadataName, StringComparison.Ordinal))
            {
                return true;
            }
        }

        return false;
    }

    private static bool HasAccessibleAttribute(Compilation compilation)
    {
        // GetTypeByMetadataName returns null when several references declare the type (common with
        // polyfill packages), so inspect every candidate and accept any the compiler can bind to.
        foreach (var type in compilation.GetTypesByMetadataName(AttributeMetadataName))
        {
            if (compilation.IsSymbolAccessibleWithin(type, compilation.Assembly))
            {
                return true;
            }
        }

        return false;
    }
}
